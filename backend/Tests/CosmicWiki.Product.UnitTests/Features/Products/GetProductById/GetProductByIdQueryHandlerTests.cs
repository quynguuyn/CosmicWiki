using CosmicWiki.Caching;
using CosmicWiki.Product.Application.Abstractions.Persistence;
using CosmicWiki.Product.Application.Features.Products.Common;
using CosmicWiki.Product.Application.Features.Products.GetProductById;
using CosmicWiki.Product.Domain.Enums;
using Microsoft.Extensions.Options;
using NSubstitute;
using Xunit;
using ProductEntity = CosmicWiki.Product.Domain.Entities.Product;

namespace CosmicWiki.Product.UnitTests.Features.Products.GetProductById;

public class GetProductByIdQueryHandlerTests
{
    private readonly IProductRepository _productRepositoryMock;
    private readonly ICacheStore _cacheMock;
    private readonly IOptions<CachingOptions> _cachingOptionsMock;
    private readonly GetProductByIdQueryHandler _handler;

    public GetProductByIdQueryHandlerTests()
    {
        _productRepositoryMock = Substitute.For<IProductRepository>();
        _cacheMock = Substitute.For<ICacheStore>();
        _cachingOptionsMock = Substitute.For<IOptions<CachingOptions>>();
        
        _cachingOptionsMock.Value.Returns(new CachingOptions
        {
            ProductDetailTtlSeconds = 60,
            ProductListTtlSeconds = 60
        });

        _handler = new GetProductByIdQueryHandler(
            _productRepositoryMock,
            _cacheMock,
            _cachingOptionsMock);
    }

    [Fact]
    public async Task Handle_ShouldReturnCachedProduct_WhenProductExistsInCache()
    {
        // Arrange
        var query = new GetProductByIdQuery(Guid.NewGuid());
        var cachedProduct = new ProductResponse(
            query.Id, "SKU1", "Name1", "slug-1", "Desc", 100, 90, 10, ProductStatus.Active, Guid.NewGuid(), new List<ProductImageResponse>());
        
        var expectedCacheKey = $"product:{query.Id:N}";
        _cacheMock.GetAsync<ProductResponse>(expectedCacheKey, Arg.Any<CancellationToken>())
            .Returns(cachedProduct);

        // Act
        var result = await _handler.Handle(query, CancellationToken.None);

        // Assert
        Assert.NotNull(result);
        Assert.Equal(cachedProduct.Id, result.Id);
        
        await _productRepositoryMock.DidNotReceiveWithAnyArgs()
            .GetByIdAsync(default, default);
        
        await _cacheMock.DidNotReceiveWithAnyArgs()
            .SetAsync<ProductResponse>(default!, default!, default, default);
    }

    [Fact]
    public async Task Handle_ShouldFetchFromDbAndCache_WhenNotInCache()
    {
        // Arrange
        var query = new GetProductByIdQuery(Guid.NewGuid());
        var categoryId = Guid.NewGuid();
        var product = ProductEntity.Create("SKU1", "Name1", "slug-1", 100, 90, 10, categoryId, "Desc", ProductStatus.Active);
        
        // Mocking Id requires reflection since it's private set in AggregateRoot, but Create already generates one.
        // Let's use the one generated by Create.
        var id = product.Id;
        query = new GetProductByIdQuery(id); // Update query ID to match generated product ID
        
        var expectedCacheKey = $"product:{query.Id:N}";
        _cacheMock.GetAsync<ProductResponse>(expectedCacheKey, Arg.Any<CancellationToken>())
            .Returns((ProductResponse?)null);

        _productRepositoryMock.GetByIdAsync(query.Id, Arg.Any<CancellationToken>())
            .Returns(product);

        // Act
        var result = await _handler.Handle(query, CancellationToken.None);

        // Assert
        Assert.NotNull(result);
        Assert.Equal(product.Id, result.Id);
        
        await _productRepositoryMock.Received(1)
            .GetByIdAsync(query.Id, Arg.Any<CancellationToken>());
        
        await _cacheMock.Received(1)
            .SetAsync(
                expectedCacheKey,
                Arg.Is<ProductResponse>(r => r.Id == product.Id),
                TimeSpan.FromSeconds(60),
                Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task Handle_ShouldReturnNull_WhenNotInCacheAndNotInDb()
    {
        // Arrange
        var query = new GetProductByIdQuery(Guid.NewGuid());
        
        var expectedCacheKey = $"product:{query.Id:N}";
        _cacheMock.GetAsync<ProductResponse>(expectedCacheKey, Arg.Any<CancellationToken>())
            .Returns((ProductResponse?)null);

        _productRepositoryMock.GetByIdAsync(query.Id, Arg.Any<CancellationToken>())
            .Returns((ProductEntity?)null);

        // Act
        var result = await _handler.Handle(query, CancellationToken.None);

        // Assert
        Assert.Null(result);
        
        await _productRepositoryMock.Received(1)
            .GetByIdAsync(query.Id, Arg.Any<CancellationToken>());
        
        await _cacheMock.DidNotReceiveWithAnyArgs()
            .SetAsync<ProductResponse>(default!, default!, default, default);
    }
}
